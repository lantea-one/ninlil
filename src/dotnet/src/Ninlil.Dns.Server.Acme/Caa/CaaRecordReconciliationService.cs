using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using Ninlil.Dns.Common.Enum;
using Ninlil.Dns.Common.Wire.Records;
using Ninlil.Dns.Data.Abstractions.Entity;
using Ninlil.Dns.Data.Abstractions.Repository;
using Ninlil.Dns.Server.Authoritative.Cache;
using Ninlil.Dns.Server.Authoritative.Journal;

// Define our namespace.
namespace Ninlil.Dns.Server.Acme.Caa;

/// <summary>
///     This class is Ninlil's actual CAA (RFC 8659) reconciliation engine: it computes the
///     desired CAA record set for a zone from its own (or the global default) issuer domain, and
///     reconciles the zone's actual stored records to match, touching only records this feature
///     created itself (<see cref="RecordEntity.ManagedByFeature" /> ==
///     <see cref="RecordManagedByFeatureEnum.Caa" />) -- never an operator-added CAA record, and
///     never a zone this server does not itself own the content of.
///     <para>
///         This class lives in <c>Ninlil.Dns.Server.Acme</c>, not
///         <c>Ninlil.Dns.Server.Authoritative</c> despite depending heavily on the latter's
///         <see cref="IZoneUpdateService" />/repositories -- a deliberate, load-bearing placement,
///         not an oversight: <see cref="CaaAutoManagementOptions" /> already lives
///         in this project, and <c>Server.Acme</c> already has a one-way
///         <c>ProjectReference</c> onto <c>Server.Authoritative</c> (see
///         <see cref="AcmeDnsChallengeResponder" /> for the precedent). Putting this class in
///         <c>Server.Authoritative</c> instead would need a reference back onto
///         <c>Server.Acme</c> for <see cref="CaaAutoManagementOptions" />, an actual circular
///         project reference the build cannot express.
///     </para>
/// </summary>
/// <param name="zoneRepository">The repository used to look up the zone being reconciled.</param>
/// <param name="recordRepository">The repository this service's own CAA-record lookups run against.</param>
/// <param name="zoneUpdateService">The service every add/remove is actually applied through -- the one path this project expects zone content to change through.</param>
/// <param name="options">
///     The global default settings this service falls back to when a zone has not overridden
///     them, read live via <see cref="IOptionsMonitor{TOptions}" /> so a write to
///     <c>AcmeSettingsController.Patch</c>'s own <c>caaAutoManagement</c> fields takes effect on
///     this service's very next reconciliation, with no restart -- this class is registered
///     <c>Scoped</c>, but <see cref="IOptions{TOptions}" /> would still have cached its value
///     once, application-wide, the first time any scope resolved it, exactly the same gap
///     <c>RecursiveSettingsController</c>'s own doc comment already documents for a singleton.
/// </param>
/// <param name="logger">The logger this service records skip/reconcile decisions to.</param>
public class CaaRecordReconciliationService(
    IZoneRepository zoneRepository,
    IRecordRepository recordRepository,
    IZoneUpdateService zoneUpdateService,
    IOptionsMonitor<CaaAutoManagementOptions> options,
    ILogger<CaaRecordReconciliationService> logger
)
{
    /// <summary>
    ///     This constant contains the RFC 8659 CAA property tag this service writes -- the
    ///     "who may issue an ordinary (non-wildcard) certificate for this name" policy. Neither
    ///     an <c>issuewild</c> nor an <c>iodef</c> entry is generated by this pass; an operator who
    ///     needs either manages it as an ordinary record.
    /// </summary>
    private const string IssueTag = "issue";

    /// <summary>
    ///     This constant contains the time-to-live, in seconds, every CAA record this service
    ///     creates is given. A CAA record is consulted only at certificate-issuance time, not on
    ///     every ordinary query, so a relatively long, unremarkable TTL (matching this project's
    ///     own default TTL for most other record types) is appropriate.
    /// </summary>
    private const uint CaaRecordTimeToLiveSeconds = 3600;

    /// <summary>
    ///     This method determines whether a zone's own <see cref="ZoneEntity.Type" /> is one this
    ///     feature ever reconciles CAA records for at all -- <see cref="ZoneTypeEnum.Primary" /> or
    ///     <see cref="ZoneTypeEnum.CloudPrimary" />, the two zone types this server is itself the
    ///     source of truth for. Deliberately implemented as its own explicit, named, single-purpose
    ///     check, not an inline condition scattered across this class's own call sites -- the
    ///     <c>Primary or Secondary</c>-pattern bug class (<see cref="AuthoritativeZoneCache" />'s
    ///     own zone-type filter silently missing a newly
    ///     added answerable zone type) is the shape of mistake this method exists to make
    ///     impossible to repeat here: a future zone type this server might also come to own the
    ///     content of must be deliberately added to this one method, not discovered missing only
    ///     once a zone of that type silently never gets its CAA records reconciled.
    /// </summary>
    /// <param name="zoneType">The zone type to check.</param>
    /// <returns>
    ///     <see langword="true" /> if <paramref name="zoneType" /> is eligible for CAA
    ///     reconciliation, <see langword="false" /> otherwise (in particular, for
    ///     <see cref="ZoneTypeEnum.Secondary" />/<see cref="ZoneTypeEnum.CloudSecondary" />, whose
    ///     content is pulled from elsewhere and would simply be overwritten or fought over by the
    ///     next transfer/sync, and every other non-owning zone type).
    /// </returns>
    public static bool IsEligibleZoneType(ZoneTypeEnum zoneType) =>
        zoneType == ZoneTypeEnum.Primary || zoneType == ZoneTypeEnum.CloudPrimary;

    /// <summary>
    ///     This method reconciles a single zone's own CAA record set, identified by its own
    ///     identifier -- the entry point <see cref="CaaRecordReconciliationEventSubscriber" /> uses
    ///     in response to a <c>DnsZoneChangedEvent</c> (which already carries a zone id, not a
    ///     name).
    /// </summary>
    /// <param name="zoneId">The identifier of the zone to reconcile.</param>
    /// <param name="stoppingToken">The token used to observe cancellation of the operation.</param>
    /// <returns>What this pass actually did, or why it did nothing at all.</returns>
    public async Task<CaaReconciliationResult> ReconcileZoneAsync(
        Guid zoneId,
        CancellationToken stoppingToken = default
    )
    {
        ZoneEntity zone = await zoneRepository.GetByIdAsync(zoneId, stoppingToken);

        if (zone is null)
            return new CaaReconciliationResult(0, 0, true, "Zone not found.");

        return await ReconcileZoneAsync(zone, stoppingToken);
    }

    /// <summary>
    ///     This method reconciles a single zone's own CAA record set, identified by its own name
    ///     -- the entry point <see cref="AcmeCertificateIssuer" /> uses right after a domain's own
    ///     certificate is successfully issued or renewed, since ACME's own configuration
    ///     (<see cref="AcmeOptions.Domains" />) names a domain, not a zone id, and that domain is
    ///     always this server's own zone apex (ACME integration is scoped to
    ///     Ninlil-hosted zones only).
    /// </summary>
    /// <param name="domainName">The domain name whose zone should be reconciled.</param>
    /// <param name="stoppingToken">The token used to observe cancellation of the operation.</param>
    /// <returns>What this pass actually did, or why it did nothing at all.</returns>
    public async Task<CaaReconciliationResult> ReconcileDomainAsync(
        string domainName,
        CancellationToken stoppingToken = default
    )
    {
        ZoneEntity zone = await zoneRepository.FindByNameAsync(domainName, stoppingToken);

        if (zone is null)
        {
            logger.LogDebug(
                "'{Domain}' is not a zone this server hosts; skipping CAA reconciliation for it.",
                domainName
            );
            return new CaaReconciliationResult(
                0,
                0,
                true,
                $"'{domainName}' is not a zone this server hosts."
            );
        }

        return await ReconcileZoneAsync(zone, stoppingToken);
    }

    /// <summary>
    ///     This method does the actual work, once a zone has already been loaded: checking
    ///     eligibility, resolving the issuer domain, diffing the desired CAA record set against
    ///     what this feature previously created, and applying the difference through
    ///     <see cref="IZoneUpdateService" />.
    /// </summary>
    private async Task<CaaReconciliationResult> ReconcileZoneAsync(
        ZoneEntity zone,
        CancellationToken stoppingToken
    )
    {
        if (!IsEligibleZoneType(zone.Type))
            return new CaaReconciliationResult(
                0,
                0,
                true,
                $"Zone type '{zone.Type}' is not eligible for CAA reconciliation -- only Primary/CloudPrimary zones are."
            );

        bool enabled = zone.AutoManageCaaRecords ?? options.CurrentValue.DefaultEnabled;

        if (!enabled)
            return new CaaReconciliationResult(
                0,
                0,
                true,
                "CAA auto-management is not enabled for this zone, and the global default is currently off."
            );

        string issuerDomain = string.IsNullOrWhiteSpace(zone.CaaIssuerDomain)
            ? options.CurrentValue.DefaultIssuerDomain
            : zone.CaaIssuerDomain;

        if (string.IsNullOrWhiteSpace(issuerDomain))
        {
            logger.LogDebug(
                "Zone '{ZoneName}' has CAA auto-management enabled but no issuer domain is "
                    + "resolved (neither its own CaaIssuerDomain nor "
                    + "CaaAutoManagementOptions.DefaultIssuerDomain is set); skipping "
                    + "reconciliation rather than writing a CAA record with an empty issuer.",
                zone.Name
            );
            return new CaaReconciliationResult(
                0,
                0,
                true,
                "CAA auto-management is enabled but no issuer domain is resolved (neither this "
                    + "zone's own issuer domain nor the global default is set)."
            );
        }

        IReadOnlyList<RecordEntity> existingRecordsAtApex = await recordRepository.FindByNameAsync(
            zone.Id,
            zone.Name,
            DnsResourceRecordTypeEnum.Caa,
            stoppingToken
        );

        // Only a record this feature itself created is ever eligible to be touched -- an
        // operator-added CAA record (ManagedByFeature is null, even if it happens to be a CAA
        // record at the exact same name) is never inspected for a match, never removed, and
        // never counted against the desired set below.
        List<RecordEntity> managedRecords =
        [
            .. existingRecordsAtApex.Where(record =>
                record.ManagedByFeature == RecordManagedByFeatureEnum.Caa
            ),
        ];

        RecordEntity matchingRecord = managedRecords.FirstOrDefault(record =>
            MatchesDesiredIssueRecord(record, issuerDomain)
        );

        List<RecordEntity> recordsToRemove =
        [
            .. managedRecords.Where(record => !ReferenceEquals(record, matchingRecord)),
        ];
        List<RecordEntity> recordsToAdd = matchingRecord is null
            ? [BuildDesiredIssueRecord(zone, issuerDomain)]
            : [];

        if (recordsToAdd.Count == 0 && recordsToRemove.Count == 0)
            return new CaaReconciliationResult(0, 0, false, null);

        try
        {
            await zoneUpdateService.ApplyChangesAsync(
                zone.Id,
                recordsToAdd,
                recordsToRemove,
                null,
                stoppingToken
            );

            logger.LogInformation(
                "Reconciled CAA records for zone '{ZoneName}': added {Added}, removed {Removed}.",
                zone.Name,
                recordsToAdd.Count,
                recordsToRemove.Count
            );
        }
        catch (InvalidOperationException exception)
        {
            // A zone with no SOA record yet (freshly created, not yet bootstrapped with its own
            // first record) cannot have its serial bumped -- exactly the same "zone exists but
            // has no content yet" state BootstrapZoneAsync exists to fill. Reconciliation simply
            // has nothing to do yet; the zone's very next content change re-fires
            // DnsZoneChangedEvent and gives this service another chance.
            logger.LogDebug(
                exception,
                "Could not reconcile CAA records for zone '{ZoneName}' yet -- it may not have an "
                    + "SOA record to advance.",
                zone.Name
            );
            return new CaaReconciliationResult(0, 0, false, null);
        }

        return new CaaReconciliationResult(recordsToAdd.Count, recordsToRemove.Count, false, null);
    }

    /// <summary>
    ///     This method checks whether an existing, feature-managed record already expresses
    ///     exactly the desired policy -- a non-critical <c>issue</c> tag naming the resolved
    ///     issuer domain -- so a reconciliation pass that finds nothing to do performs no write
    ///     at all (avoiding a pointless <see cref="Core.Events.DnsZoneChangedEvent" /> republish
    ///     that would otherwise re-trigger this very same reconciliation forever).
    /// </summary>
    private static bool MatchesDesiredIssueRecord(RecordEntity record, string issuerDomain) =>
        RecordEntityCodec.DecodeTypedData(record) is CaaRecordData data
        && !data.IsCritical
        && string.Equals(data.Tag, IssueTag, StringComparison.OrdinalIgnoreCase)
        && string.Equals(data.Value, issuerDomain, StringComparison.OrdinalIgnoreCase);

    /// <summary>
    ///     This method builds the one CAA record this feature creates for a zone: a non-critical
    ///     <c>issue</c> tag, at the zone's own apex, naming the resolved issuer domain.
    /// </summary>
    private static RecordEntity BuildDesiredIssueRecord(ZoneEntity zone, string issuerDomain) =>
        new()
        {
            Id = Guid.NewGuid(),
            ZoneId = zone.Id,
            Name = zone.Name,
            Type = DnsResourceRecordTypeEnum.Caa,
            Class = DnsClassEnum.Internet,
            TimeToLiveSeconds = CaaRecordTimeToLiveSeconds,
            DataJson = Ninlil.Common.Serializer.JsonSerializer.Serialize(
                typeof(CaaRecordData),
                new CaaRecordData(false, IssueTag, issuerDomain)
            ),
            ManagedByFeature = RecordManagedByFeatureEnum.Caa,
            CreatedAtUtc = DateTimeOffset.UtcNow,
        };
}

using Ninlil.Dns.Common.Enum;

// Define our namespace.
namespace Ninlil.Dns.Data.Abstractions.Entity;

/// <summary>
///     This class represents a person or service account that can sign in to Ninlil. Its
///     shape deliberately mirrors the fields ASP.NET Core Identity expects of a user store, so
///     that the identity layer built on top of this repository can adapt it to
///     <c>IUserStore&lt;TUser&gt;</c> and its related interfaces without needing a second,
///     parallel copy of the same data.
/// </summary>
public class UserEntity : AuditableEntityBase
{
    /// <summary>
    ///     This property contains the sign-in name the user types, exactly as they typed it.
    /// </summary>
    public string UserName { get; set; }

    /// <summary>
    ///     This property contains <see cref="UserName" />, upper-invariant, so that sign-in
    ///     lookups can be indexed and compared without depending on the database's own collation
    ///     rules for case sensitivity.
    /// </summary>
    public string NormalizedUserName { get; set; }

    /// <summary>
    ///     This property contains the friendly name shown for the user throughout the
    ///     administration console, separate from the credentials they sign in with.
    /// </summary>
    public string DisplayName { get; set; }

    /// <summary>
    ///     This property contains the user's e-mail address, used for notifications and for
    ///     e-mail-based two-factor authentication.
    /// </summary>
    public string Email { get; set; }

    /// <summary>
    ///     This property contains <see cref="Email" />, upper-invariant, for the same reason as
    ///     <see cref="NormalizedUserName" />.
    /// </summary>
    public string NormalizedEmail { get; set; }

    /// <summary>
    ///     This property indicates whether <see cref="Email" /> has been verified by the user
    ///     following a confirmation link or code.
    /// </summary>
    public bool EmailConfirmed { get; set; }

    /// <summary>
    ///     This property contains the user's password, already salted and hashed. The plain-text
    ///     password is never stored anywhere.
    /// </summary>
    public string PasswordHash { get; set; }

    /// <summary>
    ///     This property contains a random value that changes whenever the user's credentials
    ///     change (password, e-mail, and so on), so that any previously-issued token which
    ///     embeds this stamp is automatically invalidated the next time it is checked.
    /// </summary>
    public string SecurityStamp { get; set; }

    /// <summary>
    ///     This property contains a random value used to detect if two requests tried to update
    ///     the same user record at the same time, so the second write can be rejected instead of
    ///     silently overwriting the first.
    /// </summary>
    public string ConcurrencyStamp { get; set; }

    /// <summary>
    ///     This property contains the user's phone number, used for SMS-based notifications.
    /// </summary>
    public string PhoneNumber { get; set; }

    /// <summary>
    ///     This property indicates whether <see cref="PhoneNumber" /> has been verified.
    /// </summary>
    public bool PhoneNumberConfirmed { get; set; }

    /// <summary>
    ///     This property indicates whether the user must supply a second authentication factor
    ///     (TOTP or e-mail) in addition to their password.
    /// </summary>
    public bool TwoFactorEnabled { get; set; }

    /// <summary>
    ///     This property contains the encrypted TOTP shared secret used to validate the codes
    ///     generated by the user's authenticator app, defined by RFC 6238. It is
    ///     <see langword="null" /> until the user finishes enrolling a TOTP authenticator.
    /// </summary>
    public string TwoFactorTotpSecretEncrypted { get; set; }

    /// <summary>
    ///     This property contains the user's current set of single-use two-factor recovery codes,
    ///     semicolon-joined and then encrypted as one opaque blob -- the same
    ///     "join, then encrypt the whole thing" shape ASP.NET Core Identity's own default
    ///     <c>UserStore</c> uses for this exact feature, adapted here since this project's own
    ///     store does not implement a general-purpose token store to layer it on top of. Replaced
    ///     wholesale by <c>NinlilDnsUserStore.ReplaceCodesAsync</c> every time a fresh batch is
    ///     generated, and rewritten (with the redeemed code removed) every time one is used. It is
    ///     <see langword="null" /> until the caller has generated a batch at least once.
    /// </summary>
    public string TwoFactorRecoveryCodesEncrypted { get; set; }

    /// <summary>
    ///     This property contains the UTC date and time at which an active lockout ends, or
    ///     <see langword="null" /> if the user is not currently locked out.
    /// </summary>
    public DateTimeOffset? LockoutEndUtc { get; set; }

    /// <summary>
    ///     This property indicates whether this user account can be locked out after too many
    ///     failed sign-in attempts.
    /// </summary>
    public bool LockoutEnabled { get; set; }

    /// <summary>
    ///     This property contains the number of consecutive failed sign-in attempts since the
    ///     last successful one, used to decide when to trigger a lockout.
    /// </summary>
    public int AccessFailedCount { get; set; }

    /// <summary>
    ///     This property indicates whether an administrator has disabled this account. A disabled
    ///     account is rejected at sign-in regardless of whether its credentials are correct.
    /// </summary>
    public bool IsDisabled { get; set; }

    /// <summary>
    ///     This property contains this user's own color-palette override for the Angular admin
    ///     SPA's theming engine. <see langword="null" /> (the default for every account) inherits
    ///     this host's own global default, <c>AppearanceOptions.Palette</c>.
    /// </summary>
    public UiThemePaletteEnum? PreferredPalette { get; set; }

    /// <summary>
    ///     This property contains this user's own light/dark mode override for the Angular admin
    ///     SPA's theming engine. <see langword="null" /> (the default for every account) inherits
    ///     this host's own global default, <c>AppearanceOptions.Mode</c>.
    /// </summary>
    public UiThemeModeEnum? PreferredMode { get; set; }

    /// <summary>
    ///     This property names the external identity provider this account was provisioned
    ///     through -- currently only the fixed literal <c>"Oidc"</c>, written by
    ///     <c>OidcUserProvisioningService</c> the first time this account signs in through this
    ///     server's own generic OpenID Connect federation. <see langword="null" /> for every
    ///     ordinary local account (the overwhelming majority), including every account that
    ///     existed before this feature did. Kept separate from <see cref="ExternalSubjectId" />
    ///     rather than folded into a single "external account" flag so a future second external
    ///     provider kind has somewhere to record which one applies, without overloading this
    ///     field's own meaning.
    /// </summary>
    public string ExternalIdentityProvider { get; set; }

    /// <summary>
    ///     This property contains the external identity provider's own immutable <c>sub</c>
    ///     (subject) claim for this account -- the value <c>OidcUserProvisioningService</c> looks
    ///     an account up by on every subsequent sign-in, deliberately never by e-mail address,
    ///     since an e-mail address can be reused or reassigned by the identity provider over time
    ///     in a way its own subject identifier never is. <see langword="null" /> for every local
    ///     account, alongside <see cref="ExternalIdentityProvider" />.
    /// </summary>
    public string ExternalSubjectId { get; set; }

    /// <summary>
    ///     This property is <see langword="null" /> for every ordinary account -- the overwhelming
    ///     majority. It is set only when the cluster's own identity/RBAC federation mechanism
    ///     genuinely detects two different nodes independently creating an account with the same
    ///     <see cref="UserName" /> while unable to see each other (a real network partition), and
    ///     this account is the one the deterministic last-write-wins tie-break
    ///     (<c>ClusterSyncConflictResolver.IncomingWins</c>) decided should lose that collision. A
    ///     losing account is never silently dropped or silently merged: it is renamed (a
    ///     <c>-conflict-&lt;shortnodeid&gt;</c> suffix appended to its original username) and this
    ///     field is set to a human-readable explanation of what happened and when -- surfaced to an
    ///     administrator via <c>UserSummary.ClusterConflictNote</c> in both the REST API and the
    ///     Angular admin SPA's own user list, so the rename is genuinely visible, not just a log
    ///     line. Cleared only by an administrator explicitly editing the account; nothing in this
    ///     project ever clears it automatically.
    /// </summary>
    public string ClusterConflictNote { get; set; }
}

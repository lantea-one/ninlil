/**
 * Fills `IconSetService` with `coreUiIcons` before the first render. `app.config.ts` uses it for
 * the running console, and specs use it where a test bed is reset inside a test (a reset drops
 * the registration that `src/test-setup.spec.ts` adds to every test bed).
 */
export function provideCoreUiIcons(): EnvironmentProviders {
  return provideAppInitializer(() => {
    inject(IconSetService).icons = coreUiIcons;
  });
}
